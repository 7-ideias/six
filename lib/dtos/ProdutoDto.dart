class ProdutoDto {
  late String _nomeProduto;
  late String _precoDeCusto;
  late String _precoDeVenda;

  String get nomeProduto => _nomeProduto;
  set nomeProduto(String value) => _nomeProduto = value;
  String get precoDeCusto => _precoDeCusto;
  set precoDeCusto(String value) => _precoDeCusto = value;
  String get precoDeVenda => _precoDeVenda;
  set precoDeVenda(String value) => _precoDeVenda = value;


}
